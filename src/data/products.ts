function slugify(value: string) {
  return value
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

/** Catalogue snapshot date — keeps "newest" ordering stable across builds. */
const CATALOGUE_DATE = new Date("2025-06-01T00:00:00.000Z");

function daysAgo(days: number) {
  const d = new Date(CATALOGUE_DATE);
  d.setUTCDate(d.getUTCDate() - days);
  return d.toISOString();
}

const DEFAULT_SHIPPING = site.shippingBlurb;

function build(s: Seed, index: number): Product {
  const flags = new Set(s.flags ?? []);

  return {
    id: `prd_${String(index + 1).padStart(4, "0")}`,
    name: s.name,
    slug: slugify(s.name),
    category: s.category,
    description: s.desc,
    shortDescription: s.short,
    price: s.price,
    compareAtPrice: s.compare,
    images: s.imgs.map((id) => photo(id, 1200)),
    thumbnail: photo(s.imgs[0], 800),
    variants: s.variants ?? [],
    sku: `CX-${s.category.slice(0, 3).toUpperCase()}-${String(index + 1).padStart(3, "0")}`,
    stock: s.stock ?? 24,
    featured: flags.has("featured"),
    bestSeller: flags.has("best"),
    newArrival: flags.has("new"),
    trending: flags.has("trending"),
    brand: s.brand ?? "ChineXmall",
    material: s.material ?? "See product details",
    dimensions: s.dimensions ?? "See product details",
    weight: s.weight ?? "0.5 kg",
    shippingInfo: DEFAULT_SHIPPING,
    whatsIncluded: s.includes ?? [`1 × ${s.name}`],
    details: s.details ?? [
      "Brand new and factory sealed",
      "Directly imported — no middlemen",
      "Quality-checked before dispatch",
      "7-day easy returns",
    ],
    colorFacet: s.color,
    productType: s.type,
    /* The starting catalogue ships untagged — tags are created and applied
       from the dashboard. */
    tags: [],
    rating: s.rating ?? 4.5,
    reviewCount: s.reviews ?? 20,
    createdAt: daysAgo(s.age ?? 60),
  };
}


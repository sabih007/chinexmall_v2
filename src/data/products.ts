function colorOption(names: SwatchName[], imageAware = false): VariantOption {
  return {
    id: "color",
    name: "Color",
    type: "color",
    values: names.map((n, i) => ({
      value: n,
      label: n[0].toUpperCase() + n.slice(1),
      hex: SWATCH[n],
      available: true,
      ...(imageAware ? { imageIndex: Math.min(i, 1) } : {}),
    })),
  };
}

function sizeOption(values: { label: string; delta?: number }[]): VariantOption {
  return {
    id: "size",
    name: "Size",
    type: "size",
    values: values.map((v) => ({
      value: v.label.toLowerCase().replace(/\s+/g, "-"),
      label: v.label,
      priceDelta: v.delta ?? 0,
      available: true,
    })),
  };
}

function packOption(values: { label: string; delta?: number }[]): VariantOption {
  return {
    id: "pack",
    name: "Pack size",
    type: "pack",
    values: values.map((v) => ({
      value: v.label.toLowerCase().replace(/\s+/g, "-"),
      label: v.label,
      priceDelta: v.delta ?? 0,
      available: true,
    })),
  };
}

